import type { ServiceTypeSlug, VehicleType } from "@/lib/types/domain";
import { formatAmount, usd } from "./price-format";

/**
 * The dispatch (trip) fee, in whole USD: what it costs to send a technician
 * to the customer's location. It is added ONCE per dispatched job, on top of
 * the service price, and is never the whole cost of a job (owner's pricing
 * brief, 2026-11-03).
 *
 * This is the only place the figure is written. Every price display, expected
 * total, FAQ answer, text message and email derives it from here, so a change
 * is one edit. src/lib/content/pricing.ts holds the helpers that format it.
 */
export const DISPATCH_FEE = 19;

/**
 * One published SERVICE price, in whole USD. It never includes the dispatch
 * fee, which is shown separately and added once per job.
 *
 * Numbers rather than display strings, so the site, the request form, the
 * texts and the emails all format the same figure the same way and can add
 * the dispatch fee to it:
 *
 *   { min: 49, max: 75 }      "$49–$75"     a range
 *   { min: 75, from: true }   "From $75"    an open-ended starting price
 *   { min: 70 }               "$70"         a single figure
 */
export interface PriceLine {
  /** Tier name. Omitted on a service's headline (first) line. */
  label?: string;
  min: number;
  /** Top of the range. */
  max?: number;
  /** An open-ended starting price: "From $75". */
  from?: boolean;
  note?: string;
  /**
   * This line is the price for requests with this vehicle type (the semi
   * truck jump start), so the request form total and the texts use it.
   */
  vehicleType?: VehicleType;
}

/**
 * Service prices that FAQ answers quote. Named once here so an answer and the
 * price line it describes cannot disagree.
 */
export const BATTERY_REPLACEMENT: PriceLine = { min: 239, note: "eligible vehicles and batteries" };
export const JUMP_START_SEMI: PriceLine = { label: "Semi trucks and 18-wheelers", min: 90, from: true, vehicleType: "semi_truck" };
export const LOCKOUT_TRUNK: PriceLine = { label: "Keys locked in the trunk", min: 120 };
export const SPARE_TIRE_CHANGE: PriceLine = { min: 50, from: true, note: "using the spare carried in your vehicle" };
export const TIRE_REPLACEMENT: PriceLine = { min: 129, from: true, note: "tire availability varies" };

/** "from $90, plus the $19 dispatch fee" — service price first, fee on its own. */
function quote(line: PriceLine): string {
  return `${formatAmount(line, "–", "from")}, plus the ${usd(DISPATCH_FEE)} dispatch fee`;
}

/**
 * A photograph of the service being performed.
 *
 * `src` points at the .webp sibling generated by scripts/optimize-images.mjs.
 * `width`/`height` are the file's NATIVE pixel dimensions — every slot that
 * renders one of these must stay at or below that width. These photographs
 * are small (612x408, and one 408x612 portrait); stretching one across a wide
 * container looks cheap and undoes the impression the picture is there to make.
 */
export interface ServicePhoto {
  src: string;
  alt: string;
  width: number;
  height: number;
}

export interface ServiceContent {
  slug: ServiceTypeSlug;
  name: string;
  shortName: string;
  needsDestination: boolean;
  summary: string;
  heroLine: string;
  problem: string;
  whileYouWait: string[];
  whatWeNeed: string[];
  faqs: { q: string; a: string }[];
  /**
   * Published service prices, without the dispatch fee. The
   * first line is the headline price (cards, badges, texts); any further line
   * is a variant priced differently, e.g. keys locked in the trunk.
   */
  priceLines?: PriceLine[];
  /**
   * What the service price covers, shown with it, so the customer can see the
   * dispatch fee is the trip and the service price is the work. Each one says
   * only what that service already promises.
   */
  priceCovers?: string;
  /** Qualifier shown beneath the price block. */
  priceNote?: string;
  /**
   * The price is advertised on its own, with no "+ $19 dispatch" beside it
   * (owner, 2026-11-07, for battery replacement). The fee is still charged:
   * the customer is told it, with the total, when they choose to book the
   * service (the battery total dialog) and again on the request form before
   * sending. Explanations of fees (FAQs, the pricing page) still state it.
   */
  feeAtBooking?: boolean;
  /** Photographs of this service being performed, for a constrained grid. */
  photos?: ServicePhoto[];
}

